# -*- coding: utf-8 -*-
"""core/borders.py — Ф49 «ГРАНИЦЫ» (день-9, 24.11): честная карта того,
куда дом НЕ ходит.

Самопознание («изучи себя») рассказывает, что Марфа УМЕЕТ; границы —
зеркальный орган: чего дом НЕ ДЕЛАЕТ никогда. Секрет сильной позиции —
не только возможности, но и явные запреты: Создатель видит забор целиком,
цифры и пути — из закона дома (config), не из выдумки модуля.
"""
from __future__ import annotations

from pathlib import Path

from core import config


def render() -> str:
    """«границы» — карта запретов дома из закона (config), не из памяти."""
    home = Path(config.HOME_DIR)
    lines = [
        "ГРАНИЦЫ ДОМА (закон, не настроение):",
        "  · дом живёт в %s — наружу не выходит: "
        "файлы ищет и взвешивает только внутри, чуланы (models, venv, "
        "llama.cpp, .git) — их хозяин сам знает" % home,
        "  · порт %d — запрет старого дома (правило 6.4): не трогаем "
        "никогда" % config.PORT_FORBIDDEN,
        "  · VRAM — хозяин глаза (порт %d, Qwen2.5-VL): танцы видеопамяти "
        "— только по резолюции Создателя; CPU — хозяин мозг (%d, 30B)"
        % (config.PORT_EYES, config.PORT_BRAIN),
        "  · слуги по вызову не живут вечно: кодер (%d) и whisper-мост "
        "(%d) — просыпаются на дело и уходят спать"
        % (config.PORT_CODER, config.PORT_WHISPER),
        "  · токены и ключи — только в .env; в чат и в код не попадают "
        "никогда (Ф105), калитку открывает слово, которого даже мозг "
        "не видел",
        "  · облака, Telegram, внешние вызовы — холодильник: включение "
        "только резолюцией Создателя, память не уезжает из дома",
        "  · панель (%d) — лицо дома: слушает только 127.0.0.1"
        % config.PORT_WEB,
    ]
    return "\n".join(lines)
