from __future__ import annotations

import json
import re
import time
from pathlib import Path
from typing import Optional

from core import config

EXECUTOR = "Марфа"          # кто читает перед действием и отвечает


def _author() -> str:
    """Автор закона — кто говорит с домом сейчас (круг знакомства Ф2);
    файла нет — Илья, Создатель канона (ядро личности)."""
    try:
        from core import people
        return people.get_name() or "Илья"
    except Exception:
        return "Илья"


def _load() -> list[dict]:
    """Читать орган; битый/нет файла — честная пустота, не крах."""
    try:
        raw = Path(config.RULES_FILE).read_text(encoding="utf-8")
        rec = json.loads(raw)
        if isinstance(rec, dict):
            items = rec.get("rules", [])
        else:
            items = rec
        return [r for r in items if isinstance(r, dict) and r.get("text")]
    except (OSError, ValueError):
        return []


def _save(items: list[dict]) -> bool:
    """Записать орган; не записалось — False (правило всё равно
    действует до рестарта: воля важнее бухгалтерии, как в №27)."""
    try:
        p = Path(config.RULES_FILE)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps({"rules": items}, ensure_ascii=False,
                                indent=1), encoding="utf-8")
        return True
    except OSError:
        return False


def _norm(text: str) -> str:
    """Нормализация для сверки дублей: без регистра/ё/пунктуации."""
    s = (text or "").lower().replace("ё", "е")
    return re.sub(r"[^a-zа-я0-9\s]", "", s).strip()


def count() -> int:
    return len(_load())


def save(text: str, memory=None) -> str:
    """Записать закон: автор Создатель, исполнитель Марфа, дата — из
    живых часов дома. Дубль — честное «уже есть», номер не растёт.
    Двойная запись: строгий орган + память с тегом «правило»."""
    text = (text or "").strip().strip('«»"\'').strip()
    if not text:
        return ("что за правило? скажи «запиши правило: <текст>» — "
                "закон ляжет с автором и исполнителем")
    items = _load()
    norm = _norm(text)
    for r in items:
        if _norm(r.get("text", "")) == norm:
            return ("такое правило уже есть — №%d от %s. Автор — %s, "
                    "исполнитель — я. Посмотреть все — «правила»"
                    % (r.get("n", 0), r.get("created", "?"),
                       r.get("author", "Илья")))
    author = _author()
    rule = {
        "n": len(items) + 1,
        "text": text,
        "author": author,
        "executor": EXECUTOR,
        "created": time.strftime("%d.%m.%Y"),
    }
    items.append(rule)
    ok = _save(items)
    # двойная запись: память с тегом «правило» (RAG найдёт закон в
    # разговоре); упавшая база закон не роняет — файл уже цел
    noted = ""
    if memory is not None:
        try:
            memory.remember(text, tags=["правило", "закон"],
                            importance=2.0)
            noted = " И положила копию в долговременную память."
        except Exception:
            noted = ""
    reply = ("правило №%d записано. Автор — %s, исполнитель — я: читаю "
             "перед действием и отвечаю за него. Дата — %s, из живых "
             "часов дома.%s Отменить может Создатель — «отмени правило "
             "№%d»" % (rule["n"], author, rule["created"], noted,
                       rule["n"]))
    if not ok:
        reply += (" (файл органа не записался — правило живо до "
                  "рестарта, расскажи архитектору)")
    return reply


def render() -> str:
    """Список законов: №, дата, автор, исполнитель, текст. Пусто —
    честная подсказка, не выдумка «у меня нет правил»."""
    items = _load()
    if not items:
        return ("правил ещё нет. Скажи «запиши правило: <текст>» — "
                "закон ляжет с автором (Создатель), исполнителем (я) "
                "и датой из живых часов дома")
    lines = ["Законы нашего дома — %d:" % len(items)]
    for r in items:
        lines.append("№%s · %s · автор %s, исполнитель %s — %s"
                     % (r.get("n", "?"), r.get("created", "?"),
                        r.get("author", "Илья"),
                        r.get("executor", EXECUTOR), r.get("text", "")))
    lines.append("Исполнитель — я: читаю их перед действием. Отменить "
                 "закон может только Создатель: «отмени правило №N»")
    return "\n".join(lines)


def show(n: int) -> str:
    """Один закон целиком; нет такого — честное «не было»."""
    for r in _load():
        if int(r.get("n", 0)) == n:
            return ("правило №%d от %s: %s\nАвтор — %s, исполнитель — "
                    "я. Читаю его перед действием и отвечаю за него."
                    % (n, r.get("created", "?"), r.get("text", ""),
                       r.get("author", "Илья")))
    return ("правила №%d нет — у меня законов: %d. Посмотри все: "
            "«правила»" % (n, count()))


def cancel(n: int) -> str:
    """Отменить закон №N (право Создателя); нет такого — честно."""
    items = _load()
    for i, r in enumerate(items):
        if int(r.get("n", 0)) == n:
            gone = items.pop(i)
            if not _save(items):
                return ("правило №%d снято, но файл органа не "
                        "записался — после рестарта закон вернётся, "
                        "расскажи архитектору" % n)
            return ("правило №%d снято: «%s». Осталось законов: %d"
                    % (n, gone.get("text", ""), len(items)))
    return ("правила №%d не было — отменять нечего. У меня законов: %d"
            % (n, count()))


def state_line() -> str:
    """Строка для состояния дома: мозг ЗНАЕТ, что законы есть и кто
    исполнитель. Нет законов — пустая строка (не шумим, №38 учит:
    каждая строка состояния стоит токенов)."""
    n = count()
    if n <= 0:
        return ""
    return ("правила дома: %d закон%s, автор — Создатель, исполнитель "
            "— я; список — «правила»" % (n, "" if n % 10 == 1 and
                                         n % 100 != 11 else "ов"))


def parse_number(payload: str) -> Optional[int]:
    """Payload вида «№3» / «3» / «N=3» — номер закона (для показа),
    не текст нового правила. Не номер — None."""
    m = re.match(r"^[№#\s]*(\d{1,3})$", (payload or "").strip())
    if m:
        return int(m.group(1))
    m = re.match(r"^[Nn]\s*[=]\s*(\d{1,3})$", (payload or "").strip())
    if m:
        return int(m.group(1))
    return None
