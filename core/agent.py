def _norm_echo(s: str) -> str:
    """Нормализация для сверки эха: без регистра, ё, пунктуации
    и лишних пробелов — «Стать лучше…» и «стать лучше!» одно эхо.
    """
    s = str(s or "").lower().replace("ё", "е")
    s = re.sub(r"[«»\"'()\[\]{}.,;:!?…\-–—_/\\]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def _action_is_empty(action: dict) -> bool:
    """Ф80: действие без аргументов — «баланс: ОК» без текста.

    Живой лог: мозг звал check_brackets/code_patch с пустыми или
    пробельными аргументами — инструмент честно отвечал своей
    шпаргалкой, а ход Создателя сгорал. True — все значения args
    пусты/пробельны (или args нет вовсе): переспросим с уколом.

    РАУНД 4 №14: 0 и False — ЗНАЧЕНИЯ, а не пустота. {"offset": 0}
    и {"recursive": False} — настоящие аргументы; раньше они считались
    промахом и получали укол вместо работы. Пустота — только None,
    пустая строка/пробелы, пустой список/словарь.
    """
    args = action.get("args") if isinstance(action, dict) else None
    if not isinstance(args, dict) or not args:
        return True
    for v in args.values():
        if isinstance(v, str):
            if v.strip():
                return False
        elif isinstance(v, bool):
            return False
        elif isinstance(v, (int, float)):
            return False
        elif v:
            return False
    return True


def _assistant_texts(history, limit: int = 2) -> list:
    """РАУНД 4 №15: последние N ответов Марфы (с конца, свежие первыми).

    Эхо сверялось только с ПОСЛЕДНИМ ответом — цикл A→B→A проходил
    насквозь: третий ход повторял первый, а сверка видела второй.
    Теперь смотрим два последних: короткий цикл ловится честно.
    H9: ход приходит и в формате мозга (content), и в формате
    DialogStore (text) — берём оба, кто первый непустой.
    """
    out: list = []
    for t in reversed(history or []):
        if isinstance(t, dict) and t.get("role") == "assistant":
            content = t.get("content")
            if not (isinstance(content, str) and content.strip()):
                content = t.get("text")
            if isinstance(content, str) and content.strip():
                out.append(content)
                if len(out) >= limit:
                    break
    return out


def _last_assistant_text(history) -> str:
    """Последний ответ Марфы в истории (совместимость с каноном)."""
    got = _assistant_texts(history, 1)
    return got[0] if got else ""


# Короткие ответы («Согласна», «Да», «не знаю») повторяются честно —
# Создатель сам требует односложные ответы на прямые вопросы; эхо —
# это дословный повтор ДЛИННОГО текста (в живом логе — 400+ символов)
_ECHO_MIN_LEN = 60


def _is_echo(answer: str, last_assistant: str) -> bool:
    """Ответ повторяет прошлый ответ Марфы: дословно (как прежде) или
    ПОЧТИ (Ф164 — вариация одного шаблона: слова те же, порядок другой).
    Короткие — мимо: односложность на прямые вопросы честна."""
    return (_norm_check(answer, last_assistant)
            or _is_echo_soft(answer, last_assistant))


def _norm_check(answer: str, last_assistant: str) -> bool:
    """Дословное эхо прежним законом (нормализация + порог длины)."""
    a, b = _norm_echo(answer), _norm_echo(last_assistant)
    return bool(a) and bool(b) and len(a) >= _ECHO_MIN_LEN and a == b


