def _nudge_empty_for(raw: str) -> str:
    """Пустой укол с диагнозом из сырой улики прошлого ответа.

    База (_NUDGE_EMPTY) остаётся при любой болезни — якоря анти-эхо
    держатся за её слова; диагноз дописывается хвостом и говорит
    модели, КАКАЯ пустота случилась и каким должен быть формат.
    """
    ev = (raw or "").strip()
    if any(k in ev for k in ('"ответ"', "«ответ»", "'ответ'")):
        why = ("В прошлой попытке ответ лежал под русским ключом — дом "
               "читает только ключ \"answer\", латиницей. ")
    elif "null" in ev:
        why = ("В прошлой попытке поле \"answer\" было null — null не "
               "доходит до Создателя. ")
    elif '""' in ev or "«»" in ev:
        why = ("В прошлой попытке поле \"answer\" было пустой строкой — "
               "пустота до Создателя не доходит. ")
    else:
        why = ""
    return (_NUDGE_EMPTY + " " + why
            + 'Формат: {"answer": "текст"} — ключ латиницей, '
              "значение непустое.")


def _salvage_answer(decision: dict, allow_with_action: bool = False) -> str:
    """Ф83 «ПЕРЕВОДЧИК КЛЮЧА» (день-12): валидный JSON, в котором
    ответ лежит под ЧУЖИМ ключом ("ответ", "response", "reply",
    "text") — прочитать, а не ронять ход.

    Живой лог 24.11: «почему или проверка?» — 21 ток генерации и
    «пустой ответ» в чате. Мозг ОТВЕТИЛ — но поле назвал не так,
    и дом сделал вид, что слов не было. ADR-002 цел: JSON валиден,
    регулярок нет, выдумки нет — прочитано ТО, что мозг сказал,
    просто под другим именем поля. Спасаются только известные
    алиасы с непустым строковым значением; «мысль», «заметка» и
    прочая самодеятельность — мимо: телепатией дом не занимается.

    РАУНД 4 №9: allow_with_action=True — для МАРШРУТА ДЕЙСТВИЯ.
    Раньше при наличии action спасатель возвращал "" безусловно,
    и слова мозга под чужим ключом терялись вместе с ходом:
    Создатель видел только результат инструмента. Теперь маршрут
    действия тоже читает алиасы — «ответ не выбрасываем» доведено
    до конца.
    """
    if not isinstance(decision, dict):
        return ""
    a = decision.get("answer")
    if isinstance(a, str) and a.strip():
        return ""                       # ответ на месте — спасать нечего
    if not allow_with_action and isinstance(decision.get("action"), dict):
        return ""                       # это ход действия, не пустота
    for key in _ANSWER_KEY_ALIASES:
        v = decision.get(key)
        if isinstance(v, str) and v.strip():
            return v.strip()
    return ""


