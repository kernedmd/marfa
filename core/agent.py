    @staticmethod
    def _human_gap(ts_str: str) -> str:
        """«dd.mm HH:MM» → «минуту назад» человеческими словами.
        Битый штамп — как есть (честность прежде красоты)."""
        try:
            ts = dt.datetime.strptime(str(ts_str), "%d.%m %H:%M")
        except ValueError:
            return str(ts_str or "когда-то")
        now = dt.datetime.now()
        ts = ts.replace(year=now.year)
        if ts > now + dt.timedelta(days=1):
            ts = ts.replace(year=now.year - 1)
        mins = int((now - ts).total_seconds() // 60)
        if mins < 1:
            return "только что"
        if mins < 60:
            return "%d мин назад" % mins
        hours = int(round(mins / 60.0))
        if hours < 24:
            return ("час назад" if hours == 1 else
                    "%d ч назад" % hours)
        return str(ts_str)

    @staticmethod
    def _last_spoken() -> Optional[tuple]:
        """Последняя реплика Создателя ГОЛОСОМ: (текст, штамп) или None.
        Первые руки — сессия voice диалога (мост ушей пишет её с
        meta.voice=True; печатные ходы туда не попадают)."""
        try:
            from core.dialog import DialogStore
            store = DialogStore()
            for t in reversed(store.turns(config.VOICE_SESSION)):
                if (isinstance(t, dict) and t.get("role") == "user"
                        and isinstance(t.get("meta"), dict)
                        and t.get("meta").get("voice")):
                    text = str(t.get("text") or "").strip()
                    if text:
                        return text, str(t.get("ts") or "")
        except Exception:
            pass
        return None

    def _last_spoken_reply(self) -> str:
        """«что я говорил в микрофон» — цитата из первых рук."""
        got = self._last_spoken()
