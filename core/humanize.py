# -*- coding: utf-8 -*-
"""core/humanize.py — СЫРЫЕ ЧИСЛА ПО-ЧЕЛОВЕЧЕСКИ (Ф5, 23.11).

Урок живого лога: на «сколько памяти» Марфа выдала строку
«[68621991936, 21075320832, 69.3, 47546671104, 21075320832]» —
сырой вывод psutil, байты без перевода; на «что это значит» повторила
список. Инструмент говорил цифрами — Создатель читает людьми.

Правило: вывод инструмента остаётся ЦЕЛИКОМ (дом не прячет сырьё),
но к крупным голым числам ДОПИСЫВАЕТСЯ расшифровка с честной оговоркой
«если это байты» — дом не знает наверняка, байт это или счётчик, и не
притворяется, что знает.
"""
from __future__ import annotations

import re

# Голое целое от миллиона: не часть слова, не версия с точкой, не дробь
_BIG_RX = re.compile(r"(?<![\w.])(\d{7,})(?![\w.])")


def _fmt_bytes(n: int) -> str:
    """Байты — по-человечески: КБ/МБ/ГБ/ТБ."""
    if n >= 2 ** 40:
        return "%.1f ТБ" % (n / 2 ** 40)
    if n >= 2 ** 30:
        return "%.1f ГБ" % (n / 2 ** 30)
    if n >= 2 ** 20:
        return "%.1f МБ" % (n / 2 ** 20)
    return "%.0f КБ" % (n / 2 ** 10)


def _fmt_count(n: int) -> str:
    """Счётчик — по-человечески: млн/млрд."""
    if n >= 10 ** 9:
        return "%.1f млрд" % (n / 10 ** 9)
    return "%.1f млн" % (n / 10 ** 6)


def big_numbers(text: str) -> list[int]:
    """Крупные голые числа в порядке появления (уникальные)."""
    seen: list[int] = []
    for m in _BIG_RX.finditer(str(text or "")):
        n = int(m.group(1))
        if n not in seen:
            seen.append(n)
    return seen


def humanize_numbers(text: str, max_notes: int = 4) -> str:
    """К выводу инструмента дописать расшифровку крупным числам.

    Сырьё не трогается; в хвост идёт блок «по-человечески»: каждое
    число — с переводом (байты — с честной оговоркой). Крупных чисел
    больше max_notes — переводятся первые, остальное остаётся сырьём
    (расшифровка — помощь, не лекция). Мелких чисел (< миллиона) это
    не касается: «69.3» и «42» читаются и так.
    """
    text = str(text or "")
    nums = big_numbers(text)
    if not nums:
        return text
    notes = []
    for n in nums[:max_notes]:
        pretty = "{:,.0f}".format(n).replace(",", " ")   # 68 621 991 936
        if n >= 2 ** 30:
            notes.append("%s = %s, если это байты" % (pretty, _fmt_bytes(n)))
        elif n >= 2 ** 20:
            # серединка (миллионы): может быть счётчиком, может — байтами;
            # честность — оба прочтения, пусть Создатель выберет
            notes.append("%s = %s (или %s, если это байты)"
                         % (pretty, _fmt_count(n), _fmt_bytes(n)))
        else:
            notes.append("%s = %s" % (pretty, _fmt_count(n)))
    return (text + "\n\n(крупные числа по-человечески: "
            + "; ".join(notes)
            + ("" if len(nums) <= max_notes else "; …") + ")")
