    def _dispatch(self, user_text: str, reply_to=None,
                  history: Optional[list] = None) -> Reply:
        """Прежняя главная точка: калитка → пробуждение → рефлексы → мозг."""
        # Раунд 3, №6: калитка Создателя — тоже код, и она может споткнуться
        # (нет .env, битый конфиг). Безопасность важнее, но исключение из
        # калитки не должно убивать весь чат: урок — архитектору, ход — дальше.
        # РАУНД 4 (оставлено осознанно): это fail-open — при крахе калитки
        # кодовое слово уходит дальше по тракту. Выбрана доступность дома;
        # если Создатель решит иначе — менять на честный отказ здесь.
        try:
            hit, gate_reply = creator_gate.check(user_text)
        except Exception as e:
            _lesson("калитка-сбой", "%s: %s" % (type(e).__name__, e))
            hit, gate_reply = False, None
        if hit:
            return Reply(gate_reply, "python", "creator_gate")
        # СОН (23.11): слово Создателя будит организм — как прикосновение.
        # Рефлексы (быстрые команды) работают и в сонном окне; разговор —
        # пробуждение. Броня: упавший орган сна не роняет чат — организм
        # просто считается проснувшимся
        try:
            sleep.wake_on_message()
        except Exception:
            pass
        # Раунд 3, №4: быстрые команды зовут сенсоры, доктора, библиотекаря,
        # память и руки — любой из них может упасть. Крах быстрой команды
        # не должен ронять чат: урок летит архитектору, ответ говорит мозг
        # (медленнее, но живо) — так же, как «вычисли» прозрачно падает в мозг.
        # РАУНД 4 №1-2: именно эта броня ПРЯТАЛА два мёртвых рефлекса
        # (UnboundLocalError выглядел как «сенсор упал»). Урок теперь
        # несёт имя команды — чтобы такое было видно в журнале сразу.
        try:
            fast = self._fast(user_text)
        except Exception as e:
            _lesson("быстрая-упала", "%s: %s | команда: %.80s"
                    % (type(e).__name__, e, user_text))
            fast = None
        if fast is not None:
            return fast
        # Ф41 ПАМЯТЬ ОТВЕТОВ (день-9): повторный вопрос — Марфа помнит,
        # что отвечала, и отвечает мгновенно; честность — в первой строке
        # («Помню — уже отвечала…»), свежесть — TTL. Мозг не платит второй
        # раз за тот же вопрос. Броня: упавшая память не роняет ход —
        # вопрос честно уходит мозгу.
        try:
            remembered = answercache.lookup(user_text)
        except Exception as e:
            _lesson("память-ответов-упала", "%s: %s" % (type(e).__name__, e))
            remembered = None
        if remembered is not None:
            return Reply(remembered, "answercache", "answercache")
        # эфир: быстрые команды мгновенны, а вот мозговой трек — долгий;
        # чат обязан видеть, ЧТО происходит, пока он идёт (не молчать)
        progress.stage("собираю контекст: доктрина, воспоминания, состояние дома…")
        try:
            system_extra = self._static_system()
        except ValueError as e:
            # Закон контекста (H8 раунда 2): ядро+доктрина не влезают в
            # бюджет — это ЗАКОН дома, а не сбой сенсора. Доктрина нерушима:
            # отвечать без неё мозг не будет, честный отказ + зов архитектору
            _lesson("контекст-чп", str(e))
            return Reply("промпт не влез в закон дома (%d ток) — скажи "
                         "архитектору, вот что вышло: %s"
                         % (config.PROMPT_BUDGET_TOKENS, e), "fallback", None)
        except Exception as e:
            # Раунд 3, №10: прочий крах контекста (сенсор, RAG, клиент) —
            # не крах хода и не «мозг недоступен». Едем на статичном ядре.
            #
            # РАУНД 4 №11: запасной вызов стоял ВНЕ брони. Если падал
            # именно identity.manifest_slim() внутри ядра — второй вызов
            # падал так же, уже без защиты → 500 панели. «Ядро упасть не
            # может» — предположение, а не гарантия. Теперь две ступени
            # отката, обе под бронёй; последний рубеж — текст в коде.
            _lesson("контекст-сбой", "%s: %s" % (type(e).__name__, e))
            try:
                system_extra = self._static_core()
            except Exception as e2:
                _lesson("контекст-сбой", "ядро: %s: %s"
                        % (type(e2).__name__, e2))
                system_extra = IDENTITY + "\n\n" + SPEED_LAW + "\n\n" + TONE_LAW
        # Ф77: состояние и RAG — подвижный хвост хода (в системе им не
        # место: часы рвали бы KV-кэш префикса каждым ходом)
        turn_context = ""
        try:
            turn_context = self._turn_context(user_text)
        except Exception as e:
            _lesson("контекст-сбой", "хвост хода: %s: %s" % (type(e).__name__, e))
        progress.stage("мозг думает — кратко и по делу, ответ напечатается живьём…")
        # МОЗГ v3 «АНТИ-ЭХО»: пустой ответ и дословный повтор прошлого
        # переспрашиваются ОДИН раз с уколом; эхо и после укола — честное
        # признание, а не выдача повтора за ответ (урок живого лога 23.11).
        # РАУНД 4 №15: сверяем с ДВУМЯ последними ответами — цикл A→B→A
        # проходил насквозь, потому что сверка видела только B.
        # Ф164 (круг 26): окно ТРИ (цикл A→B→C→A из живого лога дня-15 —
        # между «У меня нет инструмента…» дважды стояли «почини что?»)
        # и в том же окне — ПОПУГАЙ ШАБЛОНОВ: шпаргалка дома, скопированная
        # мозгом из контекста, не ответ Создателю и не эхо себя — свой
        # укол и своё честное признание.
        recent_answers = _assistant_texts(history, 3)
        decision = None
        ans: str = ""
        nudge = ""
        for _attempt in (1, 2):
            try:
                decision = self.brain.ask_json(
                    user_text + nudge, system_extra=system_extra,
                    history=history,
                    max_tokens=config.BRAIN_ANSWER_TOKENS,
                    on_text=progress.preview,
                    turn_context=turn_context)
            except Exception as e:
                _lesson("мозг-недоступен", str(e))
                # Урок переписки 22.11: голое «timed out» Создатель читает как
                # поломку. Чаще это медленный Pascal-мозг, честно думающий
                # над длинным ответом, — говорим это человеческим языком.
                # Урок дня-8 (23.11): «WinError 10061» — вторая болезнь:
                # сервер мозга НЕ СЛУШАЕТ порт (выключен/грузится/команда
                # старта отвергнута) — лечение другое, и оно в подсказке.
                note = ""
                if "timed out" in str(e).lower():
                    note = (" — думал дольше %d сек и не успел. Это не поломка: "
                            "мозг честно работает, просто медленно. Спроси "
                            "покороче или повтори через минуту"
                            % config.BRAIN_TIMEOUT_SEC)
                elif is_refusal(str(e)):
                    note = (" — сервер мозга не отвечает на порту (соединение "
                            "отклонено): мозг выключен, грузится или его команду "
                            "старта отвергла сборка. Лечение: кнопка "
                            "scripts\\92_brain_fix.bat — чинит команду и поднимает "
                            "мозг; живость покажет карточка «Мозг» на панели")
                # Ф94 «ДЕЖУРНЫЙ РЕЖИМ» (круг 17, открытый вопрос №3 из
                # СТАТУСА): третья ступень fallback. Мозг мёртв — дом
                # НЕ гаснет: рефлексы не зовут его по построению, и
                # Создатель обязан это ЗНАТЬ из самого сбоя, а не
                # выяснять вслепую. Витрина — имена из identity
                # (источник один; якорь сверяет их с манифестом).
                _plain = [n for n in identity.duty_names() if "<" not in n]
                duty = (" Дежурный режим: рефлексы дома живы без мозга — "
                        + ", ".join(_plain[:6])
                        + "… скажи «что ты можешь без мозга» — покажу "
                          "витрину целиком.")
                return Reply("мозг недоступен: " + str(e) + note + duty,
                             "fallback", None)
            # РАУНД 4 №10: decision не-словарём (None, список, строка)
            # уезжал в чат сырым str(decision) — Создатель видел «None».
            # Брак формата лечится как пустота: укол, потом честный сбой.
            if not isinstance(decision, dict):
                _lesson("мозг-не-формат", "ответ не словарь: %.120s"
                        % (str(decision),))
                decision = {}
            if isinstance(decision.get("action"), dict):
                # МАРШРУТ ДЕЙСТВИЯ v2 «ответ не выбрасываем» (23.11, ночь —
                # техническая мысль Создателя: «она пишет ответ, но в чат
                # приходит эхо вызова — возможно, нормальный ответ не
                # дошёл»). Прежний маршрут молча выбрасывал answer, если
                # мозг дал ответ И действие вместе: Создатель видел
                # только результат инструмента. Теперь — ОБА: сначала
                # слова Марфы, потом сделанное. Штамп токенов — тоже на
                # этом пути: счёт честен, генерация была
                raw_ans = decision.get("answer")
                pre = ("" if raw_ans is None else
                       (raw_ans if isinstance(raw_ans, str) else str(raw_ans))).strip()
                # РАУНД 4 №9: спасатель ключа работает и здесь. Мозг мог
                # положить слова под «ответ»/«text» ВМЕСТЕ с действием —
                # раньше они терялись (Ф83 читал алиасы только на пути
                # чистого ответа). «Ответ не выбрасываем» — до конца.
                if not pre:
                    pre = _salvage_answer(decision, allow_with_action=True)
                    if pre:
                        _lesson("мозг-не-тот-ключ",
                                "прочитал под чужим ключом (с действием): %.120s"
                                % (getattr(self.brain, "last_raw", "") or ""))
                # Ф80: пусто-аргументное действие БЕЗ слов — не действие,
                # а промах («баланс: ОК» живого лога): один переспрос
                # с уколом, повторный промах — честный результат
                if (not pre and _attempt == 1
                        and _action_is_empty(decision["action"])):
                    _lesson("инструмент-без-аргументов",
                            "мозг позвал: %r" % (decision["action"],))
                    nudge = _NUDGE_TOOL
                    continue
                acted = self._act(decision["action"])
                if pre:
                    acted.text = pre + "\n\n" + acted.text
                meta = self._usage_meta()
                if meta:
                    acted.meta = meta
                return acted
            raw_ans = decision.get("answer")
            ans = "" if raw_ans is None else (
                raw_ans if isinstance(raw_ans, str) else str(raw_ans))
            # Ф83 «ПЕРЕВОДЧИК КЛЮЧА»: мозг ответил под чужим ключом —
            # прочитать ДО укола: честный ответ за одну генерацию,
            # без второй минуты ретрая (урок дня-12: 21 ток «почему
            # или проверка?» сгорел, а слова были — просто в другом поле)
            if not ans.strip():
                saved = _salvage_answer(decision)
                if saved:
                    _lesson("мозг-не-тот-ключ",
                            "прочитал под чужим ключом: %.120s"
                            % (getattr(self.brain, "last_raw", "") or ""))
                    ans = saved
            if not ans.strip() and _attempt == 1:
                _lesson("мозг-пустой-ответ", user_text[:120])
                # Ф82: укол знает болезнь — по сырой улике (Ф81) он
                # называет модели, ЧТО именно было не так: русский
                # ключ, null, пустая строка. Общий укол «ответь по
                # существу» лечил наугад — и вторая попытка
                # повторяла первую (живой лог 24.11, дважды пусто)
                nudge = _nudge_empty_for(
                    getattr(self.brain, "last_raw", ""))
                continue
            _parrot = _parroted_template(ans)
            if _attempt == 1 and (_parrot or any(
                    _is_echo(ans, prev) for prev in recent_answers)):
                _lesson("мозг-шпаргалка" if _parrot else "мозг-зацикливание",
                        user_text[:120])
                nudge = _NUDGE_PARROT if _parrot else _NUDGE_ECHO
                continue
            break
        # СКОРОСТЬ v1: штамп несёт и токены — «40,2 с · мозг · 84 ток»;
        # снова две минуты? по токенам сразу видно, кто съел время.
        # Фишка аудита-2: и ПРОМПТ-тоже — «165,8 с · мозг · 273 ток
        # · промпт 2100»: большой промпт = долгий префикс, диагноз
        # виден без консоли (штамп 22.11: 165,8 с при 273 ток — это
        # промпт так думал, а не декод разошёлся)
        usage = getattr(self.brain, "last_usage", None)
        tok = None
        ptok = None
        if isinstance(usage, dict):
            try:
                tok = int(usage.get("completion_tokens") or 0) or None
            except (TypeError, ValueError):
                tok = None
            try:
                ptok = int(usage.get("prompt_tokens") or 0) or None
            except (TypeError, ValueError):
                ptok = None
        meta: dict = {}
        if tok:
            meta["tok"] = tok
        if ptok:
            meta["ptok"] = ptok
        # Раунд 3, №9 лечится честностью дважды: пустой ответ после
        # ретрая — честный сбой с путём лечения («хвост brain пустой
        # ответ»), эхо после укола — признание («Я зациклилась»),
        # которому Создатель сам учил в живом разговоре 23.11
        if not ans.strip():
            # Ф81 (день-12): сбой несёт УЛИКУ — что мозг прислал в
            # последней попытке. «Скажи хвост brain» — это путь
            # лечения, но правда уже здесь: Создатель видит причину
            # (null? пустые кавычки? чужой ключ?) не отходя от чата
            raw_ev = (getattr(self.brain, "last_raw", "") or "").strip()
            ev = (" Вот что мозг прислал в последней попытке: "
                  + raw_ev[:160]) if raw_ev else ""
            return Reply("мозг вернулся с пустым ответом дважды — это сбой, "
                         "а не пауза. Скажи «хвост brain пустой ответ» — "
                         "покажу лог, или повтори ход." + ev, "brain", None,
                         meta=meta or None)
        if _parroted_template(ans):
            # Ф164: шпаргалка дома — не ответ. Честное признание + путь
            # лечения; кэш ответов её не помнит (повторять подсказку
            # нечего — она и так в каждом «почини»)
            return Reply("Я повторила шпаргалку дома вместо своего ответа. "
                         "Скажи «ответь иначе» — подумаю заново.",
                         "brain", None, meta=meta or None)
        if any(_is_echo(ans, prev) for prev in recent_answers):
            return Reply("Я зациклилась и повторила прошлый ответ. "
                         "Скажи «ответь иначе» — и я попробую заново.",
                         "brain", None, meta=meta or None)
        # Ф41: чистый ответ мозга ложится в память ответов — в
        # следующий раз Марфа вспомнит его мгновенно. Не помнятся:
        # действия (повторить слова без дела — врать о мире) и сбои
        # (они вернулись раньше по своим путям). Броня: память
        # упала — ход уже отвечен, просто без воспоминаний.
        try:
            answercache.store(user_text, ans)
        except Exception as e:
            _lesson("память-ответов-не-записалась",
                    "%s: %s" % (type(e).__name__, e))
        return Reply(ans, "brain", None, meta=meta or None)