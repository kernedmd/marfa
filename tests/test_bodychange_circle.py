def test_3z_announces_and_finishes():
    """Ф109: смена тела — объявление с побайтной сверкой, петля не рвётся.

    Лестница errorlevel честна: fc не смог открыть (2) — молчу, тела
    одинаковы (0) — молчу, различаются (1) — объявляю и доезжаю петлю
    на старом теле до самого ГОТОВО.
    """
    t = _text()
    sub = t[t.index(":: ---------- 3z."):t.index("\n:no_selfupdate")]
    # смена тела смотрится только после приёма bundle
    assert 'if not "%IMPORTED%"=="1" goto :no_selfupdate' in sub
    # побайтная сверка работающего тела с деревом
    assert 'fc /b "%~f0" "scripts\\80_sync_github.bat" >nul 2>&1' in sub
    # лестница: ошибка сверки (2) — раньше вывода о различии (не 1)
    assert sub.index("if errorlevel 2 goto :no_selfupdate") < \
        sub.index("if not errorlevel 1 goto :no_selfupdate")
    # объявление вслух: старое доезжает, новое — со следующего запуска
    assert "Смена тела" in sub and "до ГОТОВО" in sub \
        and "со следующего запуска" in sub
    # после метки поток продолжает петлю — чистка дома на месте
    tail = t[t.index("\n:no_selfupdate"):]
    assert ":: ---------- 3b." in tail


