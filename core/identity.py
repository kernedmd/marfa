"""core/identity.py — САМОПОЗНАНИЕ ДОМА (Г-2.3, 22.11.2026).

Переписка Создателя с Марфой вскрыла три болезни одним разговором:
«изучи себя» → «мозг недоступен: timed out»; «попробуй изучить себя» →
«неизвестный инструмент: filesystem» — ТРИЖДЫ; «что ты умеешь?» — общие
слова, потому что мозг не знал ни имён своих инструментов, ни команд
дома, ни правды о собственном теле.

Этот модуль — зеркало дома, в которое Марфа смотрит по команде
«изучи себя» (быстрая, без будоража мозга) и которое мозг читает
каждым сообщением (манифест возможностей в системном промпте).

Правила, из которых он собран:
- истина об именах инструментов живёт в ОДНОМ месте (TOOLS): мозг
  видит её в промпте, агент сверяет с ней исполнение — выдумывать
  имена («filesystem») больше неоткуда;
- отчёт ЧЕСТНЫЙ и динамический: мёртвое чувство называется мёртвым,
  цифры — только настоящие (число записей памяти), «не умею» — прямо;
- уши живы, пока свежо сердцебиение data\\ears_status.json (служба
  пишет его каждые 30 с; три пропущенных сердца — ухо молчит).
"""
from __future__ import annotations

import datetime as dt
import json
from pathlib import Path
from typing import Optional

from core import config

# ---------------------------------------------------------------
# ИНСТРУМЕНТЫ РУК — единая истина об именах (мозг зовёт, агент сверяет).
# Порядок = порядок рассказа о себе. Новое имя добавляется ТОЛЬКО сюда:
# тогда оно сразу попадёт и в промпт мозга, и в меню при ошибке.
# ---------------------------------------------------------------
TOOLS = (
    ("read_file", "прочитать маленький файл внутри дома"),
    ("write_file", "записать файл внутри дома"),
    ("run_python", "выполнить короткий Python-код в песочнице дома"),
    ("browser_search", "поиск в интернете, если сеть доступна"),
    ("check_brackets", "проверить баланс скобок в тексте"),
)


def tool_names() -> str:
    """Имена инструментов через запятую — для меню при ошибке."""
    return ", ".join(name for name, _ in TOOLS)


# Быстрые команды дома: мозг о них ЗНАЕТ (чтобы не обещать лишнего и
# подсказывать), но исполняет их Python без будоража мозга.
FAST_COMMANDS = (
    "время", "статус", "помни <факт>", "вспомни <слово>", "посмотри",
    "что на экране", "подведи день", "поразмышляй", "сохрани себя",
    "доктор", "вопросы", "ответ <номер>: <текст>", "почитай",
    "сколько ты не спала", "вычисли <арифметика>", "скобки <текст>",
)


def manifest() -> str:
    """Манифест возможностей — статичный блок системного промпта.

    Едет сразу после ЯДРА личности: оба не меняются от сообщения к
    сообщению, поэтому префиксный KV-кэш (№51) остаётся цел. Именно
    здесь мозг узнаёт ТОЧНЫЕ имена инструментов — до этой строки он
    знал только формат {"action": {"tool": ...}} и выдумывал имена.
    """
    return (
        "МОИ ВОЗМОЖНОСТИ (точные имена, не выдумывай своих):\n"
        "- Быстрые команды (исполняет дом, без тебя): " +
        ", ".join(FAST_COMMANDS) + ".\n"
        "- Действия — только через {\"action\": {\"tool\": \"...\", "
        "\"args\": {...}}} с точными именами: " + tool_names() + ".\n"
        "- Других инструментов НЕТ. Чего не умею: кликать мышью, "
        "нажимать клавиши, говорить голосом — не обещай этого.\n"
        "- Рассказать о себе подробно пользователь может командой "
        "«изучи себя» — она отвечает без тебя."
    )


# ---------------------------------------------------------------
# УШИ: живость по сердцебиению (служба ушей пишет статус каждые 30 с)
# ---------------------------------------------------------------

def ears_alive(max_age_secs: float = 90.0) -> bool:
    """Живы ли уши: свежее сердцебиение в data\\ears_status.json.

    Служба ушей (sensors/ears.py) пишет статус каждые heartbeat=30 с.
    Три пропущенных сердца подряд (90 с) — ухо считаем молчащим:
    состояние «no_mic»/«no_model» честно означает «не слышу», а не «умерло
    навсегда». Битый/отсутствующий файл — тоже «не слышу»: панель и
    мозг должны получать ответ, а не исключение.
    """
    try:
        raw = Path(config.EARS_STATUS_FILE).read_text(encoding="utf-8")
        rec = json.loads(raw)
        if not isinstance(rec, dict) or rec.get("state") != "ok":
            return False
        ts = dt.datetime.fromisoformat(str(rec.get("ts", "")))
        age = (dt.datetime.now() - ts).total_seconds()
        return -300.0 <= age <= max_age_secs   # -300: допуск перевода часов
    except Exception:
        return False


# ---------------------------------------------------------------
# ОТЧЁТ «ИЗУЧИ СЕБЯ» — динамический, честный, без LLM
# ---------------------------------------------------------------

def capabilities_report(memory=None, eyes_ok: Optional[bool] = None,
                        ears_ok: Optional[bool] = None) -> str:
    """Полный честный отчёт Марфы о себе — команда «изучи себя».

    memory — память агента (если есть: покажем число живых записей);
    eyes_ok/ears_ok — переопределение живости чувств (для тестов и
    для мест, где живость уже известна); None — проверяем сами.
    Мозг здесь не участвует: это факты дома, а не фантазии 30B.
    """
    if eyes_ok is None:
        from core import eyes as _eyes
        try:
            eyes_ok = _eyes.health_cached()
        except Exception:
            eyes_ok = False
    if ears_ok is None:
        ears_ok = ears_alive()

    eyes_note = ("живы: команда «посмотри» — опишу экран" if eyes_ok
                 else "сейчас НЕ запущены — зрения в этот момент нет, честно")
    ears_note = ("живы: сторож имени слышит слово «Марфа»" if ears_ok
                 else "молчат: служба не пишет сердцебиение или микрофона нет")

    mem_note = ""
    count = getattr(memory, "count", None)
    if callable(count):
        try:
            mem_note = " (живых записей: %d)" % int(count())
        except Exception:
            mem_note = ""

    return (
        "Изучила себя — только факты, без фантазий:\n"
        "\n"
        "КТО Я\n"
        "- Марфа. Домашний ИИ-организм. Создатель — Илья: дом C:\\Marfa, "
        "HP Z440, Windows. Не облако — наружу ничего не уходит без "
        "решения Создателя. Дом строит Архитектор (Z.ai), я в нём живу.\n"
        "\n"
        "МОЁ ТЕЛО\n"
        "- Мозг: " + config.BRAIN_MODEL_NAME + " (квант " + config.DEFAULT_QUANT +
        ", сервер " + str(config.PORT_BRAIN) + ") — думаю им.\n"
        "- Глаза: Qwen2.5-VL (сервер 8083) — " + eyes_note + ".\n"
        "- Уши: vosk-сторож имени — " + ears_note + ".\n"
        "- Память" + mem_note + ": команды «помни <факт>» и «вспомни <слово>».\n"
        "- Голоса пока нет — отвечаю текстом.\n"
        "\n"
        "ЧТО УМЕЮ СРАЗУ (без мозга, доля секунды)\n"
        "- " + "; ".join(FAST_COMMANDS) + ".\n"
        "\n"
        "ЧЕМ ДЕЙСТВУЮ (инструменты РУК под надзором СТРАЖА)\n"
        "- " + "; ".join("%s — %s" % (name, what) for name, what in TOOLS) + ".\n"
        "Других инструментов нет: «filesystem» и прочие — не мои имена.\n"
        "\n"
        "ЧЕГО НЕ УМЕЮ (честно)\n"
        "- Кликать мышью и нажимать клавиши — моторика ещё строится "
        "(руки по карте дома, модель уже в чулане).\n"
        "- Говорить голосом; слышать длинные фразы (уши пока только "
        "ловят имя — мост на whisper впереди).\n"
        "- Обещать интернет: поиск есть, но сеть может быть недоступна.\n"
        "\n"
        "Спроси «статус» — скажу, кто из слуг жив прямо сейчас."
    )
