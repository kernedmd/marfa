        # команду в медленный трек: «время?», «статус!», «дневник…» —
        # это те же команды. lowq — ТОЛЬКО для сравнений «вся команда»;
        # payload всегда режется с t — у «скобки ()» хвост часть текста.
        lowq = low.rstrip("?.!…,;: ")

