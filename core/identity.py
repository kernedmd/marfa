def hands_note() -> str:
    """Состояние моторной коры одной строкой (без импорта тяжёлых модулей)."""
    enabled = Path(config.HANDS_ENABLED_FILE).is_file()
    model = config.HANDS_MODEL.is_file() and config.HANDS_MMPROJ.is_file()
    if not model:
        return ("модель UI-TARS не найдена в чулане (%s) — руки спят"
                % config.HANDS_MODEL.name)
    if enabled:
        return ("моторика ВКЛЮЧЕНА резолюцией Создателя (кнопка 91): "
                "кликают и печатают по-настоящему, под стражем")
    return ("сухой режим: планируют действия, но мышь не трогают — "
            "включить моторику может Создатель (кнопка 91)")


def camera_note() -> str:
    """Готова ли камера (OpenCV установлен?)."""
    try:
        import cv2  # noqa: F401 — проверка наличия
        return "готова: «посмотри в камеру» — опишу, кто передо мной"
    except ImportError:
        return ("не готова: не поставлен OpenCV "
                "(venv\\Scripts\\pip install opencv-python)")


