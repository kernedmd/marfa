def _ears_status() -> Optional[dict]:
    """Прочитать статус службы ушей; нет/битый — None (не исключение)."""
    try:
        raw = Path(config.EARS_STATUS_FILE).read_text(encoding="utf-8")
        rec = json.loads(raw)
        return rec if isinstance(rec, dict) else None
    except Exception:
        return None


def ears_alive(max_age_secs: float = 90.0) -> bool:
    """Живы ли уши: свежее сердцебиение «ok» в data\\ears_status.json.

    Служба ушей (sensors/ears.py) пишет статус каждые heartbeat=30 с.
    Три пропущенных сердца подряд (90 с) — ухо считаем молчащим:
    состояние «no_mic»/«no_model» честно означает «не слышу», а не «умерло
    навсегда». Битый/отсутствующий файл — тоже «не слышу»: панель и
    мозг должны получать ответ, а не исключение.
    """
    rec = _ears_status()
    if rec is None or rec.get("state") != "ok":
        return False
    try:
        ts = dt.datetime.fromisoformat(str(rec.get("ts", "")))
        age = (dt.datetime.now() - ts).total_seconds()
        return -300.0 <= age <= max_age_secs   # -300: допуск перевода часов
    except Exception:
        return False


def ears_diagnosis(max_age_secs: float = 90.0) -> str:
    """Честный диагноз ушей одной строкой — для «статус» и «изучи себя».

    Урок 22.11: «молчат: служба не пишет сердцебиение или микрофона нет»
    на все случаи жизни — не диагноз, а отговорка. Служба пишет в статус
    ПРИЧИНУ (no_mic / no_model / no_sounddevice / ok + устройство) —
    называем её по имени. Так Создатель видит, чинить микрофон, модель
    или саму службу.
    """
    rec = _ears_status()
    if rec is None:
        return ("не слышу: служба ушей не пишет сердцебиение — не "
                "запущена? консоль службы покажет")
    state = str(rec.get("state", ""))
    err = str(rec.get("error", ""))[:160]
    dev = str(rec.get("device", ""))
    if state == "ok":
        try:
            ts = dt.datetime.fromisoformat(str(rec.get("ts", "")))
            age = (dt.datetime.now() - ts).total_seconds()
        except ValueError:
            age = None
        if age is not None and -300.0 <= age <= max_age_secs:
            note = "живы: сторож имени слышит «Марфа»"
            if dev:
                note += " (микрофон: %s)" % dev
            return note
        return ("не слышу: сердце службы замерло (%s с назад) — служба "
                "висит или умерла, посмотри её консоль"
                % ("?" if age is None else int(age)))
    if state == "no_mic":
        base = "не слышу: микрофон не найден или занят"
        if err:
            base += " — %s" % err
        return base
    if state == "no_model":
        base = "не слышу: модель ушей не найдена — кнопка 85_fix_ears"
        if err:
            base += " (%s)" % err
        return base
    if state == "no_sounddevice":
        return "не слышу: не поставлен sounddevice (pip install sounddevice)"
    base = "не слышу: %s" % (state or "неизвестное состояние")
    if err:
        base += " — %s" % err
    return base


