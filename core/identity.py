def hands_note() -> str:
    """Состояние моторной коры одной строкой (без импорта тяжёлых модулей).

    Руки v2 «единое зрение»: своей модели нет — руки исполняют
    координаты глаз; модель в чулане искать не нужно.
    """
    enabled = Path(config.HANDS_ENABLED_FILE).is_file()
    if enabled:
        return ("моторика ВКЛЮЧЕНА резолюцией Создателя (кнопка 91): "
                "кликают по-настоящему, под стражем")
    return ("сухой режим: называют точку клика, но мышь не трогают — "
            "включить может Создатель (кнопка 91)")


def coder_note() -> str:
    """Состояние ремонтной бригады (кодер-слуга) одной строкой."""
    try:
        from core import repair
        model = repair._find_model()
    except Exception:
        model = None
    if model is None:
        return ("модели кодера нет в чулане (qwen2.5-coder-7b) — чинить "
                "пока нечем, честно")
    return ("слуга по вызову (порт %d): «почини <файл>: <что сделать>» — "
            "напишет патч в песочницу, применяет Создатель"
            % config.PORT_CODER)


def camera_note() -> str:
    """Готова ли камера (OpenCV установлен?)."""
