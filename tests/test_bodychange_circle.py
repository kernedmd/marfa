    tree = _text()
    tree_hits = [ln for ln in tree.split("\n") if "rem BTN_VER" in ln]
    assert tree_hits == ["rem BTN_VER 3.5"], \
        "в теле кнопки должны остаться только замороженный маркер шапки: %r" % tree_hits
    # 3z жив: сверка fc /b и объявление — как закон круга 19
    sub = tree[tree.index(":: ---------- 3z."):tree.index("\n:no_selfupdate")]
    assert 'fc /b "%~f0"' in sub and "Смена тела" in sub


