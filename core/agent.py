        # — союз снимается тем же механизмом; продолжение, не оказавшееся
        # командой, честно уходит мозгу ЦЕЛИКОМ (диспетчер отдаёт исходный
        # текст, а не огрызок).
        #
        # РАУНД 4 №16: снятие обращения — ЦИКЛ, не рекурсия. «и и и и …»
        # на тысячу союзов роняло _fast RecursionError'ом (броня глотала,
        # ход уезжал в мозг). Четыре прохода хватает на «Марфа, и потом…»
        # и не даёт зациклиться на мусоре.
