def test_frozen_launcher_pinned():
    """Запускник заморожен байт-точно — якорь sha256 (закон круга 19).

    Родитель кнопки паркуется на cmd /c запускника и после возврата
    потомка читает exit /b по СТАРОМУ смещению байтов: поменяй строку
    выше — и родитель упадёт в середину чужой строки. Правки кнопки —
    только ниже :run; якорь падает и говорит об этом.
    """
    t = _text()
    zone = _frozen_zone(t)
    assert zone.lstrip().startswith("@echo off")
    assert 'cmd /c ""%TEMP%\\marfa_sync_run.bat" %*"' in zone   # танец 0a на месте
    assert hashlib.sha256(zone.encode("utf-8")).hexdigest() == FROZEN_LAUNCHER_SHA256, \
        "запускник (строки до exit /b) тронут — закон круга 19: правки только ниже :run"


def test_single_legacy_marker_never_grows():
    """Старый маркер версии — ровно один и навсегда (исторический).

    Кнопки v3.2–v3.5 искали «rem BTN_VER» и при отличии перезаписывали
    работающий файл — краш 24.11 09:32. Пока в теле кнопки есть ровно
    одна строка этого формата (замороженная «rem BTN_VER 3.5» шапки),
    старая кнопка, глядя на новое тело, видит «нет изменений» и не
    просыпается. Новые строки того формата — призрак перезаписи.
    """
    t = _text()
    hits = [ln for ln in t.split("\n") if "rem BTN_VER" in ln]
    assert hits == ["rem BTN_VER 3.5"], \
        "в теле кнопки должны остаться только замороженный маркер шапки: %r" % hits
    assert t.index("rem BTN_VER 3.5") < t.index("\n:run"), \
        "старый маркер живёт в замороженной шапке, выше :run"


