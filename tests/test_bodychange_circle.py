import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BAT = ROOT / "scripts" / "80_sync_github.bat"
PROTOCOL = ROOT / "docs" / "SYNC_PROTOCOL_v1.md"

# Хеш замороженного запускника (строки 1..62: от @echo off до exit /b
# запускника включительно). Блоб едет LF, рабочая копия Z440 — CRLF
# (.gitattributes), поэтому перед хешем переводы строк нормализуются.
FROZEN_LAUNCHER_SHA256 = "fee9bd2263e3e897283d443695858f5c68d7a241352880189e9c7ec644c46782"


def _text() -> str:
    return BAT.read_text(encoding="utf-8").replace("\r\n", "\n")


def _frozen_zone(t: str) -> str:
    """Строки от начала файла до exit /b %ERRORLEVEL% запускника."""
    end = t.index("\nexit /b %ERRORLEVEL%\n") + len("\nexit /b %ERRORLEVEL%\n")
    return t[:end]


