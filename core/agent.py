_ECHO_JACCARD = 0.75
_ECHO_CONTAIN = 0.85

# Ф164 «ПОПУГАЙ ШАБЛОНОВ»: живой лог дня-15 — на «создай инструмент»
# мозг отвечал ШПАРГАЛКОЙ дома «почини что? Формат: …» (скопировал из
