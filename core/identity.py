def bridge_note() -> str:
    """Состояние моста ушей (вторая ступень, whisper по зову) — честно.

    Зеркало обязано говорить о новом органе правду: построен ли, чего "
    "не хватает (модель в чулане / бинарник в сборке) — без выдумок
    " "про «наверное работает».
    """
    try:
        from sensors import ear_bridge
        model = ear_bridge.find_whisper_model()
        server = ear_bridge.find_whisper_server()
    except Exception:
        return "не собран (модуль моста не открылся — скажи архитектору)"
    if model and server:
        return ("построен: говори со мной вслух — «Марфа, <просьба>»; "
                "фраза придёт в чат с пометкой «услышала голосом», "
                "а ответ могу произносить голосом — «говори вслух»)")
    if model and not server:
        return ("модель whisper в чулане, но whisper-server.exe нет "
                "в сборке llama.cpp — «проверь мост» подскажет, что "
                "сделать (нужна свежая сборка)")
    return ("модели whisper нет в чулане (жду ggml-large-v3-turbo*.bin "
            "в models\\) — «проверь мост» покажет ступени")


