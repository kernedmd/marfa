        # тебе снилось?» — «а» роняло команду с органа снов в мозг,
        # который выдумал «образы, связанные с предназначением»;
        # «Марф посмотри в камеру» — короткое имя не снималось вовсе):
        # снимаются ВСЕ формы имени (Марфа/Марф/Марфочка) и частицы
        # «а/но» рядом с «и». Снимается только маршрутизация: память
        # диалога и мозг видят исходную фразу Создателя.
        for _ in range(4):
            m = re.match(r"^(?:марф(?:а|очка)?\b[\s,:;—-]*"
                         r"|(?:и|а|но)\s+)(.+)$", t, re.IGNORECASE)
